def attach_ground_truth(
    prediction_df: pd.DataFrame | None,
    ground_truth_df: pd.DataFrame | None,
) -> pd.DataFrame | None:
    """Attach churn labels to prediction rows using prediction_id."""
    if prediction_df is None:
        return None

    if ground_truth_df is None:
        return prediction_df

    if "prediction_id" not in prediction_df.columns:
        return prediction_df

    if (
        "prediction_id" not in ground_truth_df.columns
        or "churn" not in ground_truth_df.columns
    ):
        return prediction_df

    prediction_df = prediction_df.copy()

    if "churn" in prediction_df.columns:
        prediction_df = prediction_df.drop(columns=["churn"])

    return prediction_df.merge(
        ground_truth_df[["prediction_id", "churn"]],
        on="prediction_id",
        how="left",
    )


def has_labeled_data(df: pd.DataFrame) -> bool:
    """Check whether prediction rows contain labels and model outputs."""
    required = {"churn", "churn_prediction", "churn_probability"}
    return required.issubset(df.columns) and df["churn"].notna().any()


def compute_model_metrics(df: pd.DataFrame) -> dict[str, float] | None:
    """Compute metrics from labeled prediction rows."""
    if not has_labeled_data(df):
        return None

    labeled = df.dropna(
        subset=["churn", "churn_prediction", "churn_probability"]
    ).copy()

    if labeled.empty:
        return None

    y_true = labeled["churn"].astype(int)
    y_pred = labeled["churn_prediction"].astype(int)
    y_prob = labeled["churn_probability"].astype(float)

    metrics = {
        "f1_score": f1_score(y_true, y_pred, zero_division=0),
        "recall": recall_score(y_true, y_pred, zero_division=0),
        "precision": precision_score(y_true, y_pred, zero_division=0),
        "brier_score": brier_score_loss(y_true, y_prob),
    }

    metrics["roc_auc"] = (
        roc_auc_score(y_true, y_prob) if y_true.nunique() > 1 else float("nan")
    )

    return metrics


def build_probability_chart(df: pd.DataFrame) -> go.Figure:
    """Build churn probability distribution chart."""
    fig = px.histogram(
        df.dropna(subset=["churn_probability"]),
        x="churn_probability",
        nbins=25,
    )

    fig.update_layout(
        height=420,
        template="plotly_dark",
        xaxis_title="Churn Probability",
        yaxis_title="Number of Predictions",
    )

    return fig


def build_action_chart(
    df: pd.DataFrame,
) -> go.Figure:
    """Build retention action distribution chart."""
    action_counts = (
        df["action"]
        .fillna("unknown")
        .value_counts()
        .reset_index()
    )
    action_counts.columns = [
        "action",
        "count",
    ]

    action_labels = {
        "send_email": "Send Email",
        "no_action": "No Action",
        "offer_discount": "Offer Discount",
        "unknown": "Unknown",
    }

    action_counts["action_label"] = (
        action_counts["action"]
        .map(action_labels)
        .fillna(action_counts["action"])
    )

    fig = px.pie(
        action_counts,
        names="action_label",
        values="count",
        hole=0.35,
    )

    fig.update_layout(
        height=420,
        template="plotly_dark",
    )

    return fig


